// ============================================================
//  Единственный источник правды по продукции.
//  Один газ = один продукт; формы поставки живут внутри (forms).
// ============================================================

export type SupplyFormKind = 'cylinder' | 'tank';

export type SupplyForm = {
  kind: SupplyFormKind;
  label: string;
  /** Детали: объём баллонов, тип цистерн */
  note?: string;
  /** Фото формы. 2+ форм с фото → переключатель в карточке.
   *  Конвенция: cylinder может наследовать product.image; tank — своё */
  image?: string;
  alt?: string;
};

export type ProductSpecTable = {
  title: string;
  rows: { label: string; value: string }[];
};

export type Product = {
  slug: string;
  title: string;
  description: string;
  forms: [SupplyForm, ...SupplyForm[]];
  composition?: string;
  image?: string;
  alt?: string;
  /** Развёрнутое описание для страницы товара (абзацы) */
  fullDescription?: string[];
  /** Характеристики: одна или несколько таблиц */
  specs?: ProductSpecTable[];
};

